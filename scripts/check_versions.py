"""Keep dependency versions consistent with dependencies/versions.env.

dependencies/versions.env is the single source of truth for the versions of
GStreamer and OpenVINO. Files that cannot read it (Dockerfiles, workflows,
requirements files, docs, PowerShell scripts) keep a copy of the value; this
script checks every copy and, with --fix, rewrites them and regenerates
requirements/constraints.txt.

    python3 scripts/check_versions.py          # check, exit 1 on mismatch
    python3 scripts/check_versions.py --fix    # rewrite all copies
"""

import argparse
import fnmatch
import re
import subprocess  # nosec B404 - only runs "git ls-files"
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VERSIONS_FILE = REPO / "dependencies" / "versions.env"
CONSTRAINTS_FILE = REPO / "requirements" / "constraints.txt"

# Files that must never be rewritten (history, generated content).
EXCLUDED = [
    "docs/user-guide/release-notes/*",
    "dependencies/versions.env",
    "requirements/constraints.txt",
    "scripts/check_versions.py",
]

# Requirements files of DL Streamer tools; they must take OpenVINO pins from
# requirements/constraints.txt instead of pinning openvino themselves.
CONSTRAINED_REQUIREMENTS = ["scripts/download_models/requirements_*.txt"]

# Self-contained requirement files (samples generated by the coding agent and
# their template) that may be copied out of the repository, so they keep
# explicit pins and must use the nightly index while OpenVINO is a nightly.
STANDALONE_REQUIREMENTS = [
    "samples/auto_generated_samples/*/export_requirements.txt",
    ".github/skills/dlstreamer-coding-agent/assets/export-requirements-template.txt",
]


@dataclass(frozen=True)
class Rule:
    """A copy of the version 'key' matched by 'pattern' (group 'v') in 'files'."""
    key: str
    pattern: str
    files: tuple = ("*",)
    skip: tuple = ()

    def applies_to(self, path):
        """Return True if this rule checks the given repository path."""
        return (any(fnmatch.fnmatch(path, g) for g in self.files)
                and not any(fnmatch.fnmatch(path, g) for g in self.skip))


RULES = [
    # GStreamer
    Rule("GSTREAMER_VERSION", r"^ARG GST_VERSION=(?P<v>\S+)$", ("docker/*",)),
    Rule("GSTREAMER_VERSION", r"set\(DESIRED_VERSION (?P<v>[\d.]+)\)", ("dependencies/gstreamer.cmake",)),
    Rule("GSTREAMER_VERSION", r'set\(GSTREAMER_VERSION "(?P<v>[\d.]+)"\)', ("cmake/packaging/windows/*",)),
    Rule("GSTREAMER_VERSION", r'^\$GSTREAMER_VERSION = "(?P<v>[\d.]+)"', ("scripts/build_dlstreamer_dlls.ps1",)),
    Rule("GSTREAMER_VERSION", r'\$GStreamerVersion = "(?P<v>[\d.]+)"', ("dependencies/windows/*.ps1",)),
    Rule("GSTREAMER_VERSION", r"gstreamer-python==(?P<v>[\d.]+)", ("requirements/*",)),
    Rule("GSTREAMER_VERSION", r"^GSTREAMER_VERSION=(?P<v>\S+)$", ("SPECS/versions.env",)),
    Rule("GSTREAMER_VERSION", r"^Version:\s+(?P<v>\S+)$", ("SPECS/gstreamer/gstreamer.spec",)),
    Rule("GSTREAMER_VERSION", r"gstreamer(?:-devel)? >= (?P<v>[\d.]+)", ("SPECS/intel-dlstreamer/*.spec",)),
    Rule("GSTREAMER_VERSION", r"git checkout tags/(?P<v>[\d.]+) -b", (".github/workflows/*",)),
    Rule("GSTREAMER_VERSION", r"git checkout tags/[\d.]+ -b (?P<v>[\d.]+)", (".github/workflows/*",)),

    # OpenVINO GenAI archive (bundles the OpenVINO runtime)
    Rule("OPENVINO_GENAI_VERSION", r"^ARG OPENVINO_GENAI_VERSION=(?P<v>\S+)$", ("docker/*",)),
    Rule("OPENVINO_GENAI_VERSION", r"^DEFAULT_OPENVINO_GENAI_VERSION=(?P<v>\S+)$", ("tests/scripts/*",)),
    Rule("OPENVINO_GENAI_VERSION", r'^\$OPENVINO_NIGHTLY_VERSION = "(?P<v>[^"]+)"', ("scripts/*.ps1",)),
    Rule("OPENVINO_GENAI_VERSION", r"^OV_GENAI_VERSION=(?P<v>\S+)$", ("docs/*",)),
    Rule("OPENVINO_GENAI_VERSION", r"openvino_genai/packages/(?:nightly/)?(?P<v>\d[^/\s]*)/", skip=("SPECS/*",)),
    Rule("OPENVINO_GENAI_VERSION", r"openvino_genai_(?:ubuntu\d\d|windows)_(?P<v>\d[^_\s]*)_x86_64", skip=("SPECS/*",)),

    # Plain OpenVINO archive
    Rule("OPENVINO_ARCHIVE_BUILD", r"repositories/openvino/packages/(?:nightly/)?(?P<v>\d[^/\s]*)/", skip=("SPECS/*",)),
    Rule("OPENVINO_ARCHIVE_VERSION", r"openvino_toolkit_[^_\s]+_(?P<v>\d[^_\s]*)_x86_64", skip=("SPECS/*",)),

    # OpenVINO Python wheels
    Rule("OPENVINO_WHEEL_VERSION", r"\bopenvino==(?P<v>\d[^\s;,\"'`]*)"),
    Rule("OPENVINO_TOKENIZERS_WHEEL_VERSION", r"\bopenvino-tokenizers==(?P<v>\d[^\s;,\"'`]*)"),

    # OpenVINO RPM packages
    Rule("OPENVINO_RPM_VERSION", r"^ARG OPENVINO_VERSION=(?P<v>\S+)$", ("docker/fedora41/*",)),
    Rule("OPENVINO_RPM_VERSION", r"Requires: openvino-(?P<v>[\d.]+)", ("docker/fedora41/*",)),
    Rule("OPENVINO_RPM_VERSION", r"^OPENVINO_VERSION=(?P<v>\S+)$", ("SPECS/versions.env",)),
    Rule("OPENVINO_RPM_VERSION", r"dnf install -y openvino-(?P<v>[\d.]+)"),
    Rule("OPENVINO_RPM_VERSION", r"pip install openvino~=(?P<v>\d[\d.]*\d)", ("docs/*",)),
]


def load_versions():
    """Parse dependencies/versions.env into a dict."""
    versions = {}
    for line in VERSIONS_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            key, _, value = line.partition("=")
            versions[key.strip()] = value.strip()
    return versions


def render_constraints(versions):
    """Return the expected content of requirements/constraints.txt."""
    lines = [
        "# GENERATED from dependencies/versions.env by scripts/check_versions.py --fix.",
        "# Do not edit by hand.",
        "#",
        "# OpenVINO Python wheels must match the OpenVINO runtime used by DL Streamer.",
        "# Requirements files of DL Streamer tools reference this file with -c.",
        f"openvino=={versions['OPENVINO_WHEEL_VERSION']}",
        f"openvino-tokenizers=={versions['OPENVINO_TOKENIZERS_WHEEL_VERSION']}",
    ]
    return "\n".join(lines) + "\n"


def tracked_files():
    """Return the git-tracked files that may contain version copies."""
    output = subprocess.run(["git", "ls-files"], cwd=REPO, check=True,  # nosec B603 B607
                            capture_output=True, text=True).stdout
    return [p for p in output.splitlines()
            if not any(fnmatch.fnmatch(p, g) for g in EXCLUDED) and (REPO / p).is_file()]


def matches(path, globs):
    """Return True if path matches any of the glob patterns."""
    return any(fnmatch.fnmatch(path, g) for g in globs)


def check_file(path, text, versions):
    """Return (problems, fixed_text) for one file."""
    problems = []
    fixed = text
    for rule in RULES:
        if not rule.applies_to(path):
            continue
        expected = versions[rule.key]
        regex = re.compile(rule.pattern, re.MULTILINE)

        def replace(match, expected=expected, key=rule.key):
            if match.group("v") == expected:
                return match.group(0)
            line = text.count("\n", 0, match.start()) + 1
            problems.append(f"{path}:{line}: {key} is {match.group('v')}, expected {expected}")
            start, end = match.span("v")
            return match.group(0)[:start - match.start()] + expected + match.group(0)[end - match.start():]

        fixed = regex.sub(replace, fixed)

    if matches(path, CONSTRAINED_REQUIREMENTS):
        for line_no, line in enumerate(text.splitlines(), 1):
            if re.match(r"^\s*openvino(-tokenizers)?\s*[=<>~!]", line):
                problems.append(f"{path}:{line_no}: pin OpenVINO in requirements/constraints.txt, not here")
        if "requirements/constraints.txt" not in text:
            problems.append(f"{path}: missing '-c ../../requirements/constraints.txt'")

    if matches(path, CONSTRAINED_REQUIREMENTS + STANDALONE_REQUIREMENTS):
        index = versions["OPENVINO_WHEEL_EXTRA_INDEX"]
        if index and index not in text:
            problems.append(f"{path}: missing '--extra-index-url {index}' required for OpenVINO nightly wheels")
        if not index and "wheels/nightly" in text:
            problems.append(f"{path}: references the OpenVINO nightly index, but OPENVINO_WHEEL_EXTRA_INDEX is empty")
    return problems, fixed


def main():
    """Check (or fix) all version copies; return the process exit code."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fix", action="store_true", help="rewrite all copies to match versions.env")
    args = parser.parse_args()

    versions = load_versions()
    problems = []

    constraints = render_constraints(versions)
    current = CONSTRAINTS_FILE.read_text(encoding="utf-8") if CONSTRAINTS_FILE.exists() else ""
    if current != constraints:
        problems.append(f"{CONSTRAINTS_FILE.relative_to(REPO)}: out of date")
        if args.fix:
            CONSTRAINTS_FILE.write_text(constraints, encoding="utf-8")

    for path in tracked_files():
        try:
            # newline="" keeps CRLF line endings (e.g. PowerShell scripts) untouched
            with open(REPO / path, encoding="utf-8", newline="") as f:
                text = f.read()
        except (UnicodeDecodeError, OSError):
            continue
        file_problems, fixed = check_file(path, text, versions)
        problems.extend(file_problems)
        if args.fix and fixed != text:
            with open(REPO / path, "w", encoding="utf-8", newline="") as f:
                f.write(fixed)

    if not problems:
        print("All versions match dependencies/versions.env")
        return 0

    print("\n".join(problems))
    if args.fix:
        print(f"\nFixed what could be fixed automatically ({len(problems)} findings); re-run to verify.")
        return 0
    print(f"\n{len(problems)} version mismatch(es). Run: python3 scripts/check_versions.py --fix")
    return 1


if __name__ == "__main__":
    sys.exit(main())
